  const LIST = SAGESSE.concat(HUMOUR);

  const SKEY = 'ss_mantra_idx';   // sessionStorage : pensée stable sur la session
  const LKEY = 'ss_mantra_last';  // localStorage : éviter de répéter d’une session à l’autre

  function pickAvoiding(avoid) {
    let idx = Math.floor(Math.random() * LIST.length);
    if (LIST.length > 1 && idx === avoid) idx = (idx + 1) % LIST.length;
    return idx;
  }
  function remember(idx) {
    try { sessionStorage.setItem(SKEY, String(idx)); } catch (e) {}
    try { localStorage.setItem(LKEY, String(idx)); } catch (e) {}
  }

  // Pensée de la session en cours : réutilise celle déjà tirée si elle existe,
  // sinon en tire une nouvelle (en évitant celle de la session précédente).
  function forSession() {
    try {
      const saved = sessionStorage.getItem(SKEY);
      if (saved !== null && LIST[+saved]) return LIST[+saved];
    } catch (e) {}
    let last = -1;
    try { last = parseInt(localStorage.getItem(LKEY), 10); } catch (e) {}
    const idx = pickAvoiding(isNaN(last) ? -1 : last);
    remember(idx);
    return LIST[idx];
  }

  // Tirer une nouvelle pensée à la demande (clic) — évite l’actuelle.
